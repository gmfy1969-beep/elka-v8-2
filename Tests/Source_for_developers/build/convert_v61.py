# -*- coding: utf-8 -*-
"""Конвертер реальных данных ЁЛКА v6.1 -> ELKA v8.2 (realdata.json + отчёт об исправлениях)."""
import openpyxl, json, re, sys, collections
SRC=sys.argv[1] if len(sys.argv)>1 else "/data/real/v61.xlsm"
OUT=sys.argv[2] if len(sys.argv)>2 else "/data/v82/build/realdata.json"
wb=openpyxl.load_workbook(SRC,data_only=True)
fix=collections.OrderedDict()
def note(cat,txt): fix.setdefault(cat,[]).append(txt)
def clean(s):
    if s is None: return ""
    s=str(s).replace("\u00a0"," ")
    return re.sub(r"\s{2,}"," ",s).strip()
def rows(name,first=4):
    for r in wb[name].iter_rows(min_row=first,values_only=True):
        if r and r[0] not in (None,""): yield r

# ---------- справочник ----------
TYPEMAP={"Деталь":"Деталь","Материал":"Материал","Тара":"Материал","Полуфабрикат":"Полуфабрикат",
 "Объединение":"Объединение","Вариантный родитель":"Вариантный родитель","Вариантное изделие":"Вариантный родитель",
 "Некомплектный узел":"Некомплектный ПФ","Некомплектное изделие":"Некомплектный ПФ"}
raw=list(rows("Справочник"))
types={clean(r[0]):clean(r[2]) for r in raw}
groups={clean(r[0]):clean(r[4]) for r in raw}
nom=[]; seen=set()
for r in raw:
    code=clean(r[0]); name0=r[1] if r[1] is not None else ""; name=clean(name0)
    if code in seen: note("Дубли кодов",f"{code} — повтор удалён"); continue
    seen.add(code)
    if str(name0)!=name: note("Лишние пробелы в наименованиях",f"{code}: «{name0}» → «{name}»")
    if str(r[0])!=code: note("Лишние пробелы в кодах",f"«{r[0]}» → «{code}»")
    t0=clean(r[2]); base0=clean(r[5]); isp=clean(r[6]).replace("—","")
    if t0=="Вариант":
        t="Готовое изделие" if types.get(base0) in ("Вариантное изделие",) else "Деталь"
        base=base0
        if not isp:
            isp=code.split("_")[-1] if "_" in code else ""
            note("Не указано исполнение у варианта",f"{code}: исполнение «—» → «{isp}» (по коду)")
        note("Тип «Вариант» заменён на тип позиции + Базовый код",f"{code}: «Вариант» → «{t}», базовый код {base}, вариант {isp}")
    else:
        t=TYPEMAP.get(t0)
        if t is None: raise SystemExit("unknown type "+t0)
        if t!=t0: note("Типы приведены к справочнику v8",f"{code}: «{t0}» → «{t}»")
        base=""; 
        if isp: note("Исполнение у не-варианта очищено",f"{code}: «{isp}»"); isp=""
        if base0 and t0 not in ("Некомплектный узел","Некомплектное изделие"):
            note("Базовый код у не-варианта очищен (в v8 заполняется только у вариантов)",f"{code}: «{base0}»")
        if base0 and t0 in ("Некомплектный узел","Некомплектное изделие"):
            note("Связь ПФД с собираемым изделием перенесена на лист «Некомплектные_ПФ»",f"{code} → {base0}")
    g=clean(r[4])
    if t0=="Вариант" and (not g or g=="Исполнения"):
        g2=groups.get(base0) or g
        if g2!=g: note("Группа варианта взята от родителя",f"{code}: «{g}» → «{g2}»"); g=g2
    if not g:
        g={"Материал":"Материалы","Деталь":"Детали"}.get(t,"Прочее")
        note("Пустая группа заполнена",f"{code}: → «{g}»")
    mn=r[7]
    try: mnv=float(str(mn).replace(",",".")) if mn not in (None,"") else 0.0
    except ValueError: mnv=0.0
    if isinstance(mn,str): note("Мин. остаток записан текстом — преобразован в число",f"{code}: «{mn}» → {mnv:g}")
    mnv=int(mnv) if mnv==int(mnv) else mnv
    act="Нет" if clean(r[8])=="Нет" else "Да"
    nt=clean(r[10])
    if t0=="Тара": nt=(nt+"; " if nt else "")+"Тара (в v6.1 — тип «Тара»)"
    unit=clean(r[3]) or "шт"
    nom.append([code,name,t,unit,g,base,isp,mnv,"",act,clean(r[9]),nt])
codes={n[0] for n in nom}; ntype={n[0]:n[2] for n in nom}

# адреса по умолчанию (ЦС) по группам
GADDR={"Крепёж":"ЦС-A-01-01","Электроника":"ЦС-A-02-01","Электромеханика":"ЦС-A-02-01","Силовая установка":"ЦС-A-02-02",
 "Обтекатели":"ЦС-B-01-01","Корпус":"ЦС-B-01-02","Крыло":"ЦС-B-02-01","Силовой набор":"ЦС-B-02-02","Оптика":"ЦС-A-03-01",
 "Материалы":"ЦС-D-01-01","Упаковка":"ЦС-D-02-01","Объединённые поставки":"ЦС-C-01-01","Детали":"ЦС-A-04-01"}
for n in nom:
    if n[2] in ("Деталь","Материал","Объединение"): n[8]=GADDR.get(n[4],"")
    elif n[2]=="Полуфабрикат": n[8]="ПР-УЧ1"
    elif n[2]=="Некомплектный ПФ": n[8]="ПФД-01"
    elif n[2]=="Готовое изделие": n[8]="ГП-01"

# ---------- спецификация ----------
spec=[]
for r in rows("Спецификация"):
    p=clean(r[0]); c=clean(r[4]); q=r[7]
    if not p or not c: continue
    for x in (p,c):
        if x not in codes: note("Спецификация: неизвестный код",x)
    spec.append([p,c,float(q) if q not in (None,"") else 0,clean(r[10])])
    if ntype.get(c)=="Вариантный родитель":
        spec[-1][3]=(spec[-1][3]+"; " if spec[-1][3] else "")+"любое исполнение"
# ---------- объединения ----------
bundle=[]
for r in rows("Объединения"):
    b=clean(r[0]); c=clean(r[2])
    if not b or not c: continue
    bundle.append([b,c,float(r[4] or 0),clean(r[7])])
have={b[0] for b in bundle}
for n in nom:
    if n[2]=="Объединение" and n[0] not in have:
        m=re.match(r"(ПТ-000)(\d\d)(\d\d\d)/(\d\d)$",n[0])
        if m:
            a=m.group(1)+m.group(2)+m.group(3); bcode=m.group(1)+m.group(2)+m.group(3)[0]+m.group(4)
            if a in codes and bcode in codes:
                bundle.append([n[0],a,1.0,"состав восстановлен по коду — ПРОВЕРЬТЕ"]); bundle.append([n[0],bcode,1.0,"состав восстановлен по коду — ПРОВЕРЬТЕ"])
                note("Объединение без состава — состав восстановлен по коду (проверьте!)",f"{n[0]} = {a} ×1 + {bcode} ×1")
                continue
        note("Объединение без состава",n[0])
for b in bundle:
    for x in b[:2]:
        if x not in codes: note("Объединения: неизвестный код",x)
# ---------- некомплектные ПФ ----------
pfd=[]
for r in rows("Дефициты_ПФ"):
    pfd.append([clean(r[0]),clean(r[2]),clean(r[5]),float(r[7] or 0),clean(r[4])])
for p in pfd:
    for x in (p[0],p[1],p[2]):
        if x not in codes: note("Некомплектные ПФ: неизвестный код",x)
    if not any(s[0]==p[1] and s[1]==p[2] for s in spec): note("Некомплектные ПФ: недостающей детали нет в спецификации",f"{p[0]}: {p[2]} в {p[1]}")
# ---------- заказы ----------
orders=[]
for r in rows("Заказы"):
    d=r[1]
    orders.append([clean(r[0]),d.strftime("%Y-%m-%d") if hasattr(d,"strftime") else "",clean(r[2]),float(r[4] or 0),clean(r[11])])
# ---------- места ----------
LT={"ВК":"Контроль","ПР":"Производство"}
C1={"ЦС":"Центральный склад","ВК":"Склад входного контроля","ПС":"Производственный склад","ПР":"Производство","ПФД":"Склад некомплектных ПФ","БРАК":"Склад брака","ГП":"Склад готовой продукции"}
loc=[]
for r in rows("Места хранения"):
    c=clean(r[0]); t=clean(r[2])
    tt=LT.get(c,{"Склад":"Склад","Технический":"Транзит","Внешний":"Внешний"}.get(t,t))
    resp=clean(r[4]).replace("—","")
    loc.append([c,clean(r[1]),tt,"Да" if clean(r[3])=="Да" else "Нет",C1.get(c,""),resp,clean(r[5])])
loc.insert([l[0] for l in loc].index("РАЗБОР")+1,["КОМПЛЕКТОВКА","Комплектование объединений (техн.)","Транзит","Нет","","","Транзит: составляющие входят, объединение выходит (новое в v8.2)"])
note("Добавлено место хранения","КОМПЛЕКТОВКА — технический счёт для сборки объединения из составляющих (операции 32/33)")
# ---------- операции ----------
ops=[]
for r in rows("Операции"):
    code=clean(r[0]); nm=re.sub(r"^\d+\s+","",clean(r[1]))
    kind=clean(r[7]).replace("—","") or "Прочее"
    when=clean(r[9])
    if code=="44":
        nm="Перемещение между адресами ПФД"; when="Смена ячейки внутри ПФД. Переклассификация ПФД (смена кода дефицита) — кнопкой «Доукомплектовать / переклассифицировать ПФД»: 42+43+41"
        note("Операция 44 изменена","«Переклассификация ПФ (ПФД→ПФД)» одной строкой не меняла код. Теперь переклассификация — кнопкой (42+43+41), а 44 — смена ячейки внутри ПФД")
    if code in ("30","31"): when+=". Обычно автоматически кнопкой «Разобрать объединение»"
    if code=="07": when+=". Обычно автоматически кнопкой «Собрать»"
    if code in ("08","09"): when+=". Обычно автоматически кнопкой «Собрать» / «Доукомплектовать»"
    if code in ("40","41"): when+=". Обычно автоматически кнопкой «Собрать» (для кода ПФД)"
    if code in ("42","43"): when+=". Обычно автоматически кнопкой «Доукомплектовать / переклассифицировать ПФД»"
    ops.append([code,nm,clean(r[2]),clean(r[3]),"Да" if clean(r[4])=="Да" else "Нет","Да" if clean(r[5])=="Да" else "Нет","Да" if clean(r[6])=="Да" else "Нет",kind,"Да" if clean(r[8])!="Нет" else "Нет",when])
new=[["32","Комплектование объединения: списание составляющих","ЦС","КОМПЛЕКТОВКА","Нет","Да","Нет","Прочее","Да","Автоматически кнопкой «Скомплектовать объединение» (новое в v8.2)"],
     ["33","Комплектование объединения: приход объединения","КОМПЛЕКТОВКА","ЦС","Нет","Да","Нет","Прочее","Да","Автоматически кнопкой «Скомплектовать объединение» (новое в v8.2)"],
     ["34","Перемещение между адресами ЦС","ЦС","ЦС","Нет","Нет","Нет","Прочее","Да","Смена ячейки внутри ЦС: укажите «Адрес откуда» и «Адрес куда» (новое в v8.2)"],
     ["35","Перемещение между адресами ПС","ПС","ПС","Нет","Нет","Нет","Прочее","Да","Смена ячейки внутри ПС (новое в v8.2)"],
     ["36","Перемещение между адресами ГП","ГП","ГП","Нет","Нет","Нет","Прочее","Да","Смена ячейки на складе ГП (новое в v8.2)"]]
pos=[o[0] for o in ops].index("40")
ops[pos:pos]=new
note("Добавлены операции","32/33 — комплектование объединения; 34/35/36 — перемещение между адресами ЦС/ПС/ГП")
# ---------- адреса ----------
addr=[]
def A(a,l,z,s,y,c,cm): addr.append([a,l,z,s,y,c,"","Да",cm])
for zone,cm,st in (("A","Детали: крепёж, электроника, оптика",4),("B","Обтекатели, корпус, крыло",2),("C","Объединённые поставки",1),("D","Материалы и упаковка",2)):
    for s in range(1,st+1):
        for c in (1,2): A(f"ЦС-{zone}-{s:02d}-{c:02d}","ЦС",zone,f"{s:02d}","1",f"{c:02d}",cm)
for i in (1,2): A(f"ВК-{i:02d}","ВК","K","01","1",f"{i:02d}","Стол входного контроля")
for s in (1,2):
    for c in (1,2): A(f"ПС-{s:02d}-{c:02d}","ПС","A",f"{s:02d}","1",f"{c:02d}","Склад цеха")
A("ПР-УЧ1","ПР","У1","","","","Участок сборки узлов"); A("ПР-УЧ2","ПР","У2","","","","Участок финальной сборки")
for i in (1,2): A(f"ПФД-{i:02d}","ПФД","A","01","1",f"{i:02d}","Некомплектные ПФ")
A("БРАК-01","БРАК","Z","01","1","01","Изолятор брака")
for i in (1,2,3): A(f"ГП-{i:02d}","ГП","A",f"{i:02d}","1","01","Готовая продукция")
note("Добавлено адресное хранение","В v6.1 не было листа адресов. Создано "+str(len(addr))+" ячеек (ЦС зоны A–D, ВК, ПС, ПР, ПФД, БРАК, ГП); адрес по умолчанию назначен по группе. Адреса можно менять и добавлять")
json.dump(dict(nom=nom,spec=spec,bundle=bundle,pfd=pfd,orders=orders,loc=loc,ops=ops,addr=addr,fixes=fix),open(OUT,"w",encoding="utf-8"),ensure_ascii=False,indent=0)
print("nom",len(nom),"spec",len(spec),"bundle",len(bundle),"pfd",len(pfd),"orders",len(orders),"loc",len(loc),"ops",len(ops),"addr",len(addr))
print(collections.Counter(n[2] for n in nom))
for k,v in fix.items(): print(f"{k}: {len(v)}  e.g. {v[0]}")
