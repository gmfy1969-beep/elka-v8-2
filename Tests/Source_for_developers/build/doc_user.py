import sys; sys.path.insert(0, "/data/v82/build")
from docx_kit import Doc
IMG = "/data/v82/docs/img/"
def build(out):
    D = Doc("Руководство пользователя", "Просмотр остатков, движения, комплектности и документов — ELKA_Viewer.xlsm")
    D.h1("1. Что это")
    D.p("Книга **ELKA - просмотр** нужна, чтобы смотреть складские данные. Изменить данные в ней нельзя — их вносит оператор и публикует. Вы никак не мешаете оператору: его книгу вы не открываете.")
    D.table(["Лист", "Что показывает"], [
        ["Панель", "Дата и версия данных, кнопки: ОБНОВИТЬ ДАННЫЕ, Найти позицию, Сбросить фильтры, Открыть файл выделенной строки, Настроить папки"],
        ["Остатки", "Сколько каждой позиции на каждом складе"],
        ["Остатки_адреса", "В какой ячейке склада лежит позиция"],
        ["Движение", "Все операции: приход, перемещения, выдача в производство, сборка, отгрузка…"],
        ["Комплектность", "Сколько изделий и комплектов можно собрать и чего не хватает"],
        ["Просмотр", "Здесь показываются фото документов"],
        ["Инструкция", "Краткая инструкция"],
    ], widths=[4, 13])
    D.img(IMG + "viewer_panel.png", 15, "Рис. 1. Панель просмотрщика")
    D.h1("2. Первый запуск")
    D.steps([
        "Откройте ярлык **«ELKA - просмотр»** на рабочем столе (его создал установщик).",
        "Если вверху жёлтая полоса «Содержимое отключено» — нажмите **«Включить содержимое»**.",
        "Данные загрузятся сами. Если появилось окно «Папка публикации» — введите путь, который сообщил оператор (например \\\\SERVER\\ELKA\\Publish) и нажмите ОК. Окно «Папка архива» можно оставить пустым.",
        "На «Панели» появится дата публикации и версия.",
    ])
    D.h1("3. Как получить свежие данные")
    D.bullets(["При каждом открытии книга сама загружает последнюю публикацию.",
               "В любой момент — кнопка **«ОБНОВИТЬ ДАННЫЕ»** на «Панели».",
               "Данные — снимок на момент публикации оператором (дата на «Панели»). Нужно свежее — попросите оператора нажать «ОПУБЛИКОВАТЬ»."])
    D.h1("4. Остатки")
    D.p("Строка — позиция, столбцы — места хранения: ЦС — центральный склад, ВК — входной контроль, ПС — производственный склад, ПР — цех, ПФ — полуфабрикаты, ПФД — некомплектные ПФ, ГП — готовая продукция, БРАК — изолятор брака. Последний столбец — итого.")
    D.steps(["Найти позицию: «Панель» -> **«Найти позицию»** -> введите код (DET-001) или часть названия (кронштейн).",
             "Сбросить отбор — **«Сбросить фильтры»**.",
             "Можно пользоваться стрелками фильтра в заголовках и сортировкой, как в обычном Excel."])
    D.img(IMG + "viewer_stock.png", 17, "Рис. 2. Лист «Остатки»")
    D.h1("5. Движение")
    D.p("Каждая строка — одна позиция одного документа: дата, операция, код, наименование, количество, откуда, куда, адреса, № заказа, изделие, партия, № документа, файлы.")
    D.bullets(["По позиции — стрелка фильтра в столбце «Код».", "По заказу — «№ заказа».", "По документу — «Документ №».", "За период — «Дата» -> Фильтры по дате."])
    D.img(IMG + "viewer_moves.png", 17, "Рис. 3. Лист «Движение»")
    D.h1("6. Комплектность")
    D.p("Для каждого изделия и комплекта — компоненты, норма на 1 шт, сколько есть и на сколько изделий хватает. Строка «ИЗДЕЛИЕ» / «ОБЪЕДИНЕНИЕ» — сколько можно собрать сейчас. «ДЕФИЦИТ» — компонента не хватает даже на 1 шт.")
    D.img(IMG + "viewer_kits.png", 17, "Рис. 4. Лист «Комплектность»")
    D.h1("7. Документы и фото")
    D.steps(["На листе «Движение» **дважды щёлкните** по ячейке «Документ №» или «Файлы» нужной строки.",
             "Один файл — откроется сразу. Несколько — появится список: введите номер и нажмите ОК.",
             "Фото (JPG, PNG) показываются на листе «Просмотр»; кнопка «Открыть в программе» — в стандартном просмотрщике Windows.",
             "PDF, Word, Excel открываются программой Windows по умолчанию.",
             "Другой способ: выделите строку и нажмите «Открыть файл выделенной строки» на «Панели»."])
    D.note("«Файл не найден» — нет доступа к сетевой папке архива. Обратитесь к оператору или администратору.", "warn")
    D.h1("8. Если что-то не работает")
    D.table(["Проблема", "Решение"], [
        ["Кнопки не нажимаются", "Макросы отключены: закройте и откройте книгу, нажмите «Включить содержимое»"],
        ["«Нет файлов данных»", "Оператор ещё не публиковал или нет доступа к сети. «Настроить папки» — проверьте путь"],
        ["Данные старые", "«ОБНОВИТЬ ДАННЫЕ»; если не помогло — попросите оператора опубликовать"],
        ["Не получается изменить ячейку", "Так и задумано: листы защищены. Данные меняет только оператор"],
    ], widths=[5, 12])
    D.save(out)
if __name__ == "__main__": build(sys.argv[1])
